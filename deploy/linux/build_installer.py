#!/usr/bin/env python3
"""Bundle the public one-shot installer deploy/linux/install.sh from an explicit,
non-secret file list (the body, its helper, templates, the systemd unit and the
pinned public update keys). `--check` fails when install.sh is stale."""
import argparse
from pathlib import Path

HERE = Path(__file__).resolve().parent
SERVER = HERE.parents[1]
# (name inside the bundle, source path)
PAYLOADS = (
    ("install_body.sh", HERE / "install_body.sh"),
    ("install_lib.py", HERE / "install_lib.py"),
    ("server.env.example", HERE / "server.env.example"),
    ("server-update.json", HERE / "server-update.json"),
    ("shorebird-server.service", SERVER / "deploy" / "systemd" / "shorebird-server.service"),
    ("server-update.trusted-keys", SERVER / "signing" / "server-update.trusted-keys"),
)


def render() -> bytes:
    parts = ["""#!/usr/bin/env bash
# Generated by deploy/linux/build_installer.py from deploy/linux/install_body.sh and
# its payloads. Do not edit; run the builder. Public installer: it bundles no
# private key, credential or server source.
# Everything is defined before it runs, so a truncated download cannot execute
# a partial installer.
shorebird_server_install() (
    set -Eeuo pipefail
    umask 077
    bundle=$(mktemp -d)
    trap 'rm -rf -- "$bundle"' EXIT
"""]
    for index, (name, source) in enumerate(PAYLOADS):
        content = source.read_text(encoding="utf-8")
        marker = f"SHOREBIRD_SERVER_INSTALL_PAYLOAD_{index}_END"
        if marker in content:
            raise ValueError(f"payload delimiter collision in {source}")
        parts.append(f"    cat > \"$bundle/{name}\" <<'{marker}'\n{content.rstrip()}\n{marker}\n")
    parts.append('    bash "$bundle/install_body.sh" "$@"\n)\nshorebird_server_install "$@"\n')
    return "".join(parts).encode("utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if install.sh is stale")
    parser.add_argument("--output", type=Path, default=HERE / "install.sh")
    args = parser.parse_args()
    data = render()
    if args.check:
        if not args.output.is_file() or args.output.read_bytes() != data:
            raise SystemExit(f"{args.output} is stale; run deploy/linux/build_installer.py")
        return
    args.output.write_bytes(data)
    args.output.chmod(0o755)


if __name__ == "__main__":
    main()
